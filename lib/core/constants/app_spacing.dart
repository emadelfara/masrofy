/// Standard spacing values used across the application.
///
/// Use these constants instead of hardcoded numbers
/// to keep spacing consistent across the app.
abstract final class AppSpacing {
  AppSpacing._();

  // ---------------------------------------------------------------------------
  // Standard Spacing Values
  // ---------------------------------------------------------------------------

  /// Extra small spacing (4).
  static const double xs = 4.0;

  /// Small spacing (8).
  static const double sm = 8.0;

  /// Medium spacing (16).
  static const double md = 16.0;

  /// Large spacing (24).
  static const double lg = 24.0;

  /// Extra large spacing (32).
  static const double xl = 32.0;

  /// Extra extra large spacing (48).
  static const double xxl = 48.0;
}